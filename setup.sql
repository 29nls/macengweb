-- Isinya sudah mencakup dua perbaikan keamanan:
--   A. Proyek yang BELUM dipublikasikan tidak bisa dibaca lewat API anon
--      (policy SELECT publik hanya mengembalikan is_published != false)
--   B. Bucket profile-images hanya menerima upload file GAMBAR
--      (tanpa ini, siapa pun bisa menyimpan file apa pun ke bucket publik)
--
-- Catatan: bila Anda memakai Supabase CLI, versi incremental yang sama
